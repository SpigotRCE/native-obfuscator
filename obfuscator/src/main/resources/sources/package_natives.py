#!/usr/bin/env python3
"""Package and encrypt the native libraries into the generated jar.

This file was generated by native-obfuscator and already contains the native
directory, zip name and master key used by this particular jar.

By default it scans the directory containing this script recursively for
native libraries named like x64-windows.dll, x64-linux.so, arm64-macos.dylib
and so on, packs them into a zip, encrypts it exactly like the generated
loader expects and writes it into the jar as:

    <native_dir>/<zip_name>

Usage:
    python package_natives.py
    python package_natives.py --libs-dir path/to/libs --jar path/to/app.jar
"""

import argparse
import base64
import hashlib
import hmac
import io
import os
import re
import sys
import zipfile
from pathlib import Path

NATIVE_DIR = "$native_dir"
ZIP_NAME = "$zip_name"
MASTER_KEY = "$master_key"
RESULT_JAR = "$jar_name"

LIBRARY_RE = re.compile(r"^(x64|arm64|arm32|x86)-(windows\.dll|linux\.so|macos\.dylib)$")
SKIP_DIRS = {".git", ".svn", ".hg", "__pycache__", "node_modules"}


def hkdf_expand(key, info, length):
    """HKDF-SHA256 expand, matching the loader implementation."""
    result = bytearray()
    block = b""
    counter = 1
    while len(result) < length:
        block = hmac.new(
            key,
            block + info.encode("utf-8") + bytes([counter]),
            hashlib.sha256,
        ).digest()
        result.extend(block)
        counter += 1
    return bytes(result[:length])


def aes_cbc_encrypt(data, key, iv):
    """AES-CBC with PKCS#7 padding, using cryptography or pycryptodome."""
    try:
        from cryptography.hazmat.primitives import padding
        from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
    except ImportError:
        try:
            from Crypto.Cipher import AES
            from Crypto.Util.Padding import pad
        except ImportError:
            raise SystemExit(
                "AES support requires either 'cryptography' or 'pycryptodome'.\n"
                "Install one of them, for example: pip install cryptography"
            )
        return AES.new(key, AES.MODE_CBC, iv).encrypt(pad(data, 16))

    padder = padding.PKCS7(128).padder()
    padded = padder.update(data) + padder.finalize()
    encryptor = Cipher(algorithms.AES(key), modes.CBC(iv)).encryptor()
    return encryptor.update(padded) + encryptor.finalize()


def find_libraries(root):
    """Find native libraries under root, keeping the newest file per name."""
    libraries = {}
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [name for name in dirnames if name not in SKIP_DIRS]
        for filename in filenames:
            if not LIBRARY_RE.match(filename):
                continue
            path = Path(dirpath) / filename
            previous = libraries.get(filename)
            if previous is None or path.stat().st_mtime > previous.stat().st_mtime:
                libraries[filename] = path
    return libraries


def make_zip(libraries):
    """Create an in-memory zip whose entries are the bare library names."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for name in sorted(libraries):
            archive.write(libraries[name], arcname=name)
    return buffer.getvalue()


def replace_jar_entry(jar_path, entry_name, data):
    """Add or replace one entry in a jar without leaving duplicates."""
    temporary = jar_path.with_name(jar_path.name + ".tmp")
    try:
        with zipfile.ZipFile(jar_path, "r") as source, \
                zipfile.ZipFile(temporary, "w") as target:
            for info in source.infolist():
                if info.filename == entry_name:
                    continue
                target.writestr(info, source.read(info))
            target.writestr(entry_name, data, compress_type=zipfile.ZIP_DEFLATED)
        os.replace(temporary, jar_path)
    finally:
        if temporary.exists():
            temporary.unlink()


def resolve_jar(script_dir, argument):
    if argument:
        path = Path(argument)
        if not path.is_absolute():
            path = (Path.cwd() / path).resolve()
        return path
    baked = script_dir / RESULT_JAR
    if baked.is_file():
        return baked
    candidates = sorted(script_dir.glob("*.jar"))
    if len(candidates) == 1:
        return candidates[0]
    raise SystemExit(
        "Could not determine which jar to patch. Pass --jar <path> explicitly."
    )


def main():
    parser = argparse.ArgumentParser(
        description="Pack, encrypt and embed native libraries into the generated jar."
    )
    parser.add_argument(
        "--libs-dir",
        help="Directory to scan recursively for native libraries "
             "(default: the directory containing this script)",
    )
    parser.add_argument(
        "--jar",
        help="Jar to patch (default: the output jar generated next to this script)",
    )
    args = parser.parse_args()

    script_dir = Path(__file__).resolve().parent
    libs_root = Path(args.libs_dir).resolve() if args.libs_dir else script_dir
    jar_path = resolve_jar(script_dir, args.jar)

    if not jar_path.is_file():
        raise SystemExit("Jar not found: %s" % jar_path)
    if not libs_root.is_dir():
        raise SystemExit("Library directory not found: %s" % libs_root)

    libraries = find_libraries(libs_root)
    if not libraries:
        raise SystemExit(
            "No native libraries found under %s.\n"
            "Build them first, for example:\n"
            "  cd cpp\n"
            "  cmake --preset zig-x64-windows\n"
            "  cmake --build --preset zig-x64-windows" % libs_root
        )

    print("Native libraries:")
    for name in sorted(libraries):
        print("  %-22s %s" % (name, libraries[name]))

    plain_zip = make_zip(libraries)
    master_key = base64.b64decode(MASTER_KEY)
    aes_key = hkdf_expand(master_key, "aes-key", 16)
    aes_iv = hkdf_expand(master_key, "aes-iv", 16)
    encrypted_zip = aes_cbc_encrypt(plain_zip, aes_key, aes_iv)

    entry_name = NATIVE_DIR + "/" + ZIP_NAME
    replace_jar_entry(jar_path, entry_name, encrypted_zip)

    print()
    print("Packed %d libraries (%d bytes encrypted)" % (len(libraries), len(encrypted_zip)))
    print("Wrote %s to %s" % (entry_name, jar_path))


if __name__ == "__main__":
    main()
